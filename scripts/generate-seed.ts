/**
 * Writes supabase/seed.sql from the bundled dummy content, so the database and demo mode stay in sync.
 *   npm run seed:generate && npm run db:seed
 * Rows are upserted by id (or slug for system pages), so re-running restores the dummy content
 * without duplicating it. Delete the dummy rows from the admin dashboard when you add real ones.
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { DEFAULT_SETTINGS, PAGE_DEFAULTS } from "../src/lib/cms/defaults";
import { PAGE_SCHEMAS } from "../src/lib/cms/schema";
import {
  DEMO_CATEGORIES,
  DEMO_CUSTOM_PAGES,
  DEMO_FAQS,
  DEMO_POSTS,
  DEMO_PRODUCTS,
  DEMO_SERVICES,
} from "../src/lib/demo/catalog";

type Value = string | number | boolean | null | undefined | string[] | object;

function literal(value: Value): string {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "string") return `'${value.replace(/'/g, "''")}'`;
  if (Array.isArray(value) && value.every((v) => typeof v === "string")) {
    return value.length ? `array[${value.map((v) => literal(v)).join(", ")}]::text[]` : "'{}'::text[]";
  }
  return `${literal(JSON.stringify(value))}::jsonb`;
}

function upsert(table: string, rows: Array<Record<string, Value>>, conflict = "id", jsonColumns: string[] = []): string {
  if (!rows.length) return "";
  const columns = Object.keys(rows[0]);
  const values = rows
    .map((row) => {
      const cells = columns.map((c) => {
        const v = row[c];
        // Empty arrays in jsonb columns must stay jsonb, not text[].
        if (jsonColumns.includes(c)) return `${literal(JSON.stringify(v ?? []))}::jsonb`;
        return literal(v);
      });
      return `  (${cells.join(", ")})`;
    })
    .join(",\n");
  const updates = columns
    .filter((c) => c !== conflict && c !== "id" && c !== "created_at")
    .map((c) => `${c} = excluded.${c}`)
    .join(", ");
  return `insert into public.${table} (${columns.join(", ")}) values\n${values}\non conflict (${conflict}) do update set ${updates};\n`;
}

const strip = <T extends Record<string, unknown>>(row: T, keys: string[]) =>
  Object.fromEntries(Object.entries(row).filter(([k]) => !keys.includes(k))) as Record<string, Value>;

const AUDIT = ["created_at", "updated_at", "deleted_at"];

const systemPages = PAGE_SCHEMAS.map((p) => ({
  slug: p.slug,
  title: p.title,
  kind: "system",
  sections: PAGE_DEFAULTS[p.slug] ?? {},
  body: null,
  seo_title: null,
  seo_description: null,
  is_published: true,
}));

const sql = [
  "-- Generated by scripts/generate-seed.ts. Do not edit by hand.",
  "-- Dummy content for Crown Performance Wear; replace it from the admin dashboard.",
  "",
  `insert into public.site_settings (id, data) values (1, ${literal(DEFAULT_SETTINGS)}) on conflict (id) do nothing;`,
  "",
  upsert("categories", DEMO_CATEGORIES.map((c) => strip(c, AUDIT))),
  upsert(
    "products",
    DEMO_PRODUCTS.map((p) => strip(p, AUDIT)),
    "id",
    ["price_tiers", "specs", "images"],
  ),
  upsert("services", DEMO_SERVICES.map((s) => strip(s, AUDIT))),
  upsert("posts", DEMO_POSTS.map((p) => strip(p, AUDIT))),
  upsert("faqs", DEMO_FAQS.map((f) => strip(f, AUDIT))),
  upsert("pages", systemPages, "slug", ["sections"]),
  upsert("pages", DEMO_CUSTOM_PAGES.map((p) => strip(p, AUDIT)), "id", ["sections"]),
].join("\n");

const out = path.join(process.cwd(), "supabase", "seed.sql");
writeFileSync(out, sql);
console.log(`Wrote ${out}`);
